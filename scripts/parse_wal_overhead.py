"""
CASTLE Artifact Evaluation: WAL Overhead & Recovery Metrics Parser
==================================================================
This script generates the quantitative data for Table 1 in Section 7.4 
(Crash Recovery Determinism & Speed) of the VLDB 2027 paper.

[Academic Integrity & Data Provenance Guarantees]:
1. Immutable Data Source: The script strictly parses the raw stdout logs 
   (`crash_sim.log`) produced by the Rust `crash_simulator.rs` integration test. 
   It explicitly forbids any hardcoded performance numbers.
2. End-to-End Automation: To eliminate manual transcription errors (a common 
   source of academic misconduct or retraction), this script automatically 
   generates a LaTeX table fragment (`table_wal_metrics.tex`). Reviewers can 
   directly `\input{}` this file into the main paper manuscript.
3. Radical Transparency: The script parses and exposes CASTLE's CPU-bound 
   model rebuild time alongside its I/O Redo time, honoring the academic 
   trade-off discussed in Section 5.3 rather than hiding the computational overhead.
"""

import os
import sys
import re
import argparse
import pandas as pd

def parse_crash_sim_logs(log_file_path: str) -> pd.DataFrame:
    """
    Parses the raw log file generated by `cargo test --test crash_simulator`.
    
    Expected log line format from the Rust test harness:
    [Metrics] Index: <Name>, WAL_Size_MB: <float>, Redo_Time_s: <float>, Rebuild_Time_s: <float>
    """
    if not os.path.exists(log_file_path):
        print(f"[FATAL] Raw log file not found: {log_file_path}", file=sys.stderr)
        print("Please ensure Phase 2 of `run_all_experiments.sh` completed successfully.", file=sys.stderr)
        sys.exit(1)

    # Regex to capture strict metric outputs from the Rust logger
    pattern = re.compile(
        r"\[Metrics\] Index: (?P<index>.+?),\s*"
        r"WAL_Size_MB: (?P<wal_mb>[\d\.]+),\s*"
        r"Redo_Time_s: (?P<redo_s>[\d\.]+),\s*"
        r"Rebuild_Time_s: (?P<rebuild_s>[\d\.]+)"
    )

    records = []
    with open(log_file_path, 'r', encoding='utf-8') as f:
        for line in f:
            match = pattern.search(line)
            if match:
                index_name = match.group('index').strip()
                wal_mb = float(match.group('wal_mb'))
                redo_s = float(match.group('redo_s'))
                rebuild_s = float(match.group('rebuild_s'))
                
                # Convert MB to GB for the final paper presentation
                wal_gb = wal_mb / 1024.0
                
                records.append({
                    "Index Structure": index_name,
                    "WAL Size (GB)": f"~{wal_gb:.1f}",
                    "I/O Replay (s)": f"{redo_s:.1f}",
                    "Model Rebuild (s)": "N/A" if rebuild_s == 0.0 else f"{rebuild_s:.1f}"
                })

    if not records:
        print(f"[FATAL] No matching metric lines found in {log_file_path}.", file=sys.stderr)
        print("The Rust crash_simulator may have panicked or failed to output metrics.", file=sys.stderr)
        sys.exit(1)

    # Convert to DataFrame to ensure strict tabular formatting
    df = pd.DataFrame(records)
    
    # Canonical display mapping
    canonical_names = {
        "B+-Tree (Physical)": "B$^+$-Tree (Physical OLC)",
        "B+-Tree (Physical OLC)": "B$^+$-Tree (Physical OLC)",
        "Learned (Physical)": "Learned (Naive Physical WAL)",
        "Learned (Naive Physical WAL)": "Learned (Naive Physical WAL)",
        "XIndex (Scratch Replay)": "XIndex (Scratch Replay)",
        "FINEdex (Scratch Replay)": "FINEdex (Scratch Replay)",
        "CASTLE (Logical)": "CASTLE (Fuzzy Logical)",
        "CASTLE (Fuzzy Logical)": "CASTLE (Fuzzy Logical)",
    }
    df['Index Structure'] = df['Index Structure'].map(lambda x: canonical_names.get(x, x))

    # Enforce order: B+Tree -> Learned (Physical) -> XIndex -> FINEdex -> CASTLE
    order_mapping = {
        "B$^+$-Tree (Physical OLC)": 1,
        "Learned (Naive Physical WAL)": 2,
        "XIndex (Scratch Replay)": 3,
        "FINEdex (Scratch Replay)": 4,
        "CASTLE (Fuzzy Logical)": 5,
    }
    df['SortKey'] = df['Index Structure'].map(lambda x: order_mapping.get(x, 99))
    df = df.sort_values('SortKey').drop('SortKey', axis=1)
    
    return df

def generate_latex_table(df: pd.DataFrame, out_dir: str):
    """
    Generates a production-ready LaTeX table snippet.
    """
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "table_wal_metrics.tex")

    # Generate the LaTeX string with the booktabs format used in the VLDB paper
    latex_str = (
        "% AUTOMATICALLY GENERATED BY scripts/parse_wal_overhead.py\n"
        "% DO NOT EDIT MANUALLY. ANY CHANGES WILL BE OVERWRITTEN DURING ARTIFACT EVALUATION.\n\n"
        "\\begin{table}[t]\n"
        "  \\centering\n"
        "  \\small\n"
        "  \\caption{Crash Recovery Metrics: WAL Footprint and Recovery Time Objective Breakdown (10M Inserts, 64 Threads).}\n"
        "  \\label{tab:recovery_metrics}\n"
        "  \\begin{tabular}{lccc}\n"
        "    \\toprule\n"
        "    \\textbf{Index Structure} & \\textbf{WAL Size} & \\textbf{I/O Replay} & \\textbf{Model Rebuild} \\\\\n"
        "    \\midrule\n"
    )

    for _, row in df.iterrows():
        idx_name = row['Index Structure']
        wal = row['WAL Size (GB)']
        redo = row['I/O Replay (s)']
        rebuild = row['Model Rebuild (s)']
        rebuild_str = "N/A" if rebuild == "N/A" else f"{rebuild} s"
        
        # Highlight CASTLE in bold as per Section 7.4 of the manuscript
        if "CASTLE" in idx_name:
            latex_str += f"    \\textbf{{{idx_name}}} & \\textbf{{$\\sim${wal[1:] if wal.startswith('~') else wal} GB}} & \\textbf{{{redo} s}} & \\textbf{{{rebuild_str}}} \\\\\n"
        else:
            latex_str += f"    {idx_name} & $\\sim${wal[1:] if wal.startswith('~') else wal} GB & {redo} s & {rebuild_str} \\\\\n"

    latex_str += (
        "    \\bottomrule\n"
        "  \\end{tabular}\n"
        "\\end{table}\n"
    )

    with open(out_path, 'w', encoding='utf-8') as f:
        f.write(latex_str)
        
    print(f"[SUCCESS] LaTeX table successfully generated at: {out_path}")
    print("\n--- Extracted Data Preview ---")
    print(df.to_string(index=False))
    print("------------------------------\n")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Parse WAL Overhead Metrics and Generate LaTeX Table")
    parser.add_argument("--data-dir", required=True, help="Directory containing the raw crash_sim.log")
    parser.add_argument("--out-dir", required=True, help="Directory to output the .tex table snippet")
    args = parser.parse_args()

    log_path = os.path.join(args.data_dir, "crash_sim.log")
    
    df_metrics = parse_crash_sim_logs(log_path)
    generate_latex_table(df_metrics, args.out_dir)
