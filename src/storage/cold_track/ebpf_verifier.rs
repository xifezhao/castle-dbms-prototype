//! CASTLE eBPF Predicate Compiler & Verifier
//!
//! This module implements the strict hardware-offloading contracts defined in 
//! **Section 3.3 (The Dual-Track Execution Model: Cold Track)**.
//!
//! # The eBPF Floating-Point Constraint
//! Standard Linux eBPF verifiers and SmartNIC sandboxes strictly prohibit floating-point 
//! arithmetic and SIMD instructions to guarantee kernel safety and bounded execution times.
//! Consequently, the raw floating-point weights (slopes, intercepts, and error bounds) 
//! of the `LeafSnap` predictive models cannot be directly pushed down to the storage layer.
//!
//! # Conservative Integer Expansion
//! To resolve this, this module acts as a Just-In-Time (JIT) predicate compiler. 
//! It takes the floating-point routing boundaries evaluated on the host CPU and applies a 
//! **Conservative Integer Expansion**. The lower bound is strictly floored (`f64::floor`), 
//! and the upper bound is strictly ceiled (`f64::ceil`). 
//! 
//! This guarantees the absolute most critical invariant of DBMS pushdown filters: 
//! **Zero False Negatives**. The resulting integer bounding box may fetch a marginally 
//! wider range of records, but it mathematically guarantees that the target record is never skipped.

#![deny(missing_docs)]

use super::mini_block::EBpfBoundingBox;
use std::fmt::Debug;

/// eBPF Instruction Opcodes (Simplified subset for SmartNIC filtering)
/// Reflects standard Linux kernel `bpf_insn` architecture (linux/bpf.h).
#[allow(dead_code)]
mod bpf_opcodes {
    pub const BPF_LDX: u8 = 0x01;
    pub const BPF_DW: u8 = 0x18;
    pub const BPF_JMP: u8 = 0x05;
    pub const BPF_JGE: u8 = 0x30;
    pub const BPF_JLE: u8 = 0xb0;
    pub const BPF_EXIT: u8 = 0x90;
    pub const BPF_ALU64: u8 = 0x07;
    pub const BPF_MOV: u8 = 0xb0;
}

/// A standard 64-bit eBPF instruction format.
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BpfInsn {
    opcode: u8,
    dst_src_reg: u8,
    offset: i16,
    imm: i32,
}

/// Floating-point prediction bounds produced by the `LeafSnap` PLM model.
#[derive(Debug, Clone, Copy)]
pub struct PlmFloatBounds {
    /// The predicted minimum logical offset/key (Float)
    pub min_estimate: f64,
    /// The predicted maximum logical offset/key (Float)
    pub max_estimate: f64,
}

/// The CASTLE eBPF Compiler.
/// Translates floating-point ML models into verifiable, integer-only eBPF bytecode.
pub struct EBpfPredicateCompiler;

impl EBpfPredicateCompiler {
    /// Compiles floating-point bounds into a strict Integer Bounding Box.
    /// 
    /// # Safety & Correctness
    /// Utilizes `floor()` and `ceil()` to expand the predictive interval to the nearest 
    /// encompassing integers. Truncation (`as u64`) is explicitly avoided as it could 
    /// shrink the interval, violating the zero-false-negative contract.
    #[inline]
    pub fn generate_safe_integer_bounds(float_bounds: &PlmFloatBounds) -> EBpfBoundingBox {
        // Explicitly handle NaNs and Infinities which could crash the SmartNIC or yield corrupted queries.
        assert!(
            float_bounds.min_estimate.is_finite() && float_bounds.max_estimate.is_finite(),
            "Fatal: Predictive model generated non-finite bounds (NaN or Inf). Model is poisoned."
        );

        let safe_min = float_bounds.min_estimate.floor();
        let safe_max = float_bounds.max_estimate.ceil();

        // Floor of negative numbers is correctly handled, but we clamp to 0 
        // since storage offsets/keys are inherently unsigned in CASTLE.
        let min_key = if safe_min < 0.0 { 0 } else { safe_min as u64 };
        let max_key = safe_max as u64;

        // Generate a checksum to prevent PCIe silent data corruption (Section 3.3)
        let checksum = Self::compute_checksum(min_key, max_key);

        EBpfBoundingBox {
            min_key,
            max_key,
            checksum,
        }
    }

    /// Compiles the Integer Bounding Box into raw eBPF bytecode for SmartNIC offloading.
    ///
    /// The generated bytecode executes the equivalent of:
    /// `if (record_key >= min_key && record_key <= max_key) return KEEP; else return DROP;`
    pub fn compile_to_bytecode(bounds: EBpfBoundingBox) -> Vec<BpfInsn> {
        use bpf_opcodes::*;

        vec![
            // 1. Load target record key from context (r1) into r2
            BpfInsn { opcode: BPF_LDX | BPF_DW, dst_src_reg: 0x21, offset: 0, imm: 0 },
            
            // 2. Load min_key into r3
            BpfInsn { opcode: BPF_ALU64 | BPF_MOV, dst_src_reg: 0x30, offset: 0, imm: bounds.min_key as i32 },
            
            // 3. if (r2 < r3) goto DROP (+2)
            BpfInsn { opcode: BPF_JMP | BPF_JGE, dst_src_reg: 0x23, offset: 2, imm: 0 },
            
            // 4. Load max_key into r4
            BpfInsn { opcode: BPF_ALU64 | BPF_MOV, dst_src_reg: 0x40, offset: 0, imm: bounds.max_key as i32 },
            
            // 5. if (r2 > r4) goto DROP (+1)
            BpfInsn { opcode: BPF_JMP | BPF_JLE, dst_src_reg: 0x24, offset: 1, imm: 0 },
            
            // 6. KEEP: return 1 (True)
            BpfInsn { opcode: BPF_ALU64 | BPF_MOV, dst_src_reg: 0x00, offset: 0, imm: 1 },
            BpfInsn { opcode: BPF_JMP | BPF_EXIT, dst_src_reg: 0x00, offset: 0, imm: 0 },
            
            // 7. DROP: return 0 (False)
            BpfInsn { opcode: BPF_ALU64 | BPF_MOV, dst_src_reg: 0x00, offset: 0, imm: 0 },
            BpfInsn { opcode: BPF_JMP | BPF_EXIT, dst_src_reg: 0x00, offset: 0, imm: 0 },
        ]
    }

    /// Computes a lightweight checksum for the bounding box.
    #[inline]
    fn compute_checksum(min_key: u64, max_key: u64) -> u32 {
        let mut hash = 0x811c9dc5_u32; // FNV-1a offset basis
        
        let bytes = min_key.to_le_bytes().into_iter().chain(max_key.to_le_bytes().into_iter());
        for b in bytes {
            hash ^= b as u32;
            hash = hash.wrapping_mul(0x01000193); // FNV prime
        }
        hash
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_conservative_integer_expansion() {
        let float_bounds = PlmFloatBounds {
            min_estimate: 10.1,  // Should floor to 10
            max_estimate: 20.9,  // Should ceil to 21
        };

        let safe_box = EBpfPredicateCompiler::generate_safe_integer_bounds(&float_bounds);
        
        // Assert zero false negatives through expansion
        assert_eq!(safe_box.min_key, 10);
        assert_eq!(safe_box.max_key, 21);
    }

    #[test]
    fn test_negative_float_clamping() {
        let float_bounds = PlmFloatBounds {
            min_estimate: -5.4,  // Should clamp to 0 for unsigned bounds
            max_estimate: 15.0,
        };

        let safe_box = EBpfPredicateCompiler::generate_safe_integer_bounds(&float_bounds);
        
        assert_eq!(safe_box.min_key, 0);
        assert_eq!(safe_box.max_key, 15);
    }
    
    #[test]
    #[should_panic(expected = "Fatal: Predictive model generated non-finite bounds")]
    fn test_nan_poisoning_defense() {
        let float_bounds = PlmFloatBounds {
            min_estimate: f64::NAN,
            max_estimate: 100.0,
        };

        // This must panic to prevent silent DB corruption or SmartNIC crashes.
        let _ = EBpfPredicateCompiler::generate_safe_integer_bounds(&float_bounds);
    }
}
